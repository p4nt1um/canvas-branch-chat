import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const built=await build({stdin:{contents:"export {SiwcProvider} from './providers/siwc-provider'; export {configureSession} from './siwc/session'; export {applyRequestOptions} from './siwc/request-options';",resolveDir:process.cwd()},bundle:true,platform:'node',format:'cjs',write:false,external:['obsidian']});
const m={exports:{}}; const require=createRequire(import.meta.url);
new Function('require','module','exports',built.outputFiles[0].text)(n=>n==='obsidian'?{}:require(n),m,m.exports);
const {SiwcProvider,configureSession,applyRequestOptions}=m.exports;
const original={id:'config',providerType:'siwc',model:'original',systemPrompt:''};
const selected=applyRequestOptions(original,{model:'server-model',reasoningEffort:'high'});
assert.equal(original.model,'original'); assert.equal(original.reasoningEffort,undefined);
assert.equal(applyRequestOptions({providerType:'openai',model:'legacy'},{model:'other'}).model,'legacy');
const defaults={...original,reasoningEffort:'high'};
assert.equal(applyRequestOptions(defaults).reasoningEffort,'high');
assert.equal(applyRequestOptions(defaults,{}).reasoningEffort,'high');
assert.equal(applyRequestOptions(defaults,{reasoningEffort:''}).reasoningEffort,undefined);
assert.equal(applyRequestOptions(defaults,{reasoningEffort:'low'}).reasoningEffort,'low');
assert.equal(applyRequestOptions(defaults,{model:'other'}).reasoningEffort,undefined);
assert.equal(defaults.reasoningEffort,'high');
let posts=[];
configureSession({access:async()=>'test-token',request:async(url,init)=>{
 if(url.endsWith('/models')) return Response.json({models:[{slug:'server-model',display_name:'Server model',visibility:'list',supported_reasoning_levels:[{effort:'high'}]}]});
 posts.push(JSON.parse(init.body));
 return new Response('data: {"type":"response.output_text.delta","delta":"OK"}\n\ndata: {"type":"response.completed"}\n\n');
}});
assert.equal(await new SiwcProvider(selected).streamChat([{role:'user',content:'test'}]),'OK');
assert.equal(posts[0].model,'server-model'); assert.deepEqual(posts[0].reasoning,{effort:'high'});
assert.equal(posts[0].store,false); assert.equal(posts[0].stream,true);
await new SiwcProvider({...selected,reasoningEffort:undefined}).streamChat([{role:'user',content:'test'}]);
assert.ok(!('reasoning' in posts[1]));
await assert.rejects(new SiwcProvider({...selected,reasoningEffort:'unsupported'}).streamChat([]));
assert.equal(posts.length,2);
console.log('Per-request model/reasoning assertions passed');
